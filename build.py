#!/usr/bin/env python3
"""Build site/bank.js from the two teacher question banks.

  src/questions-units.json   Units 1-2 (Computing Systems, Networks & Internet)
  src/questions-pop.json     Pop Culture edition
  src/mc-conversions.json    multiple-choice versions of every short-answer item

The output is lightly scrambled (XOR + base64) so answers aren't readable
with View Source. It is not security, just a speed bump for curious 7th graders.
"""
import base64, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "src"
KEY = b"ctrl+alt+quest"

units = json.loads((SRC / "questions-units.json").read_text())
pop = json.loads((SRC / "questions-pop.json").read_text())
conv = json.loads((SRC / "mc-conversions.json").read_text())
banks = {"U": units, "P": pop}
missing = []


def norm(tag, q, key, value=None):
    t = q.get("type", "short")
    out = {
        "id": f"{tag}-{key}",
        "prompt": q["prompt"],
        "answer": q["answer"] if not isinstance(q["answer"], bool) else ("True" if q["answer"] else "False"),
        "explanation": q.get("explanation", ""),
        "value": value if value is not None else q.get("value", 100),
    }
    if t == "mc":
        out.update(type="mc", choices=q["choices"], answerIndex=q["answerIndex"])
    elif t == "tf":
        out.update(type="tf", choices=["True", "False"], answerIndex=0 if q["answer"] else 1)
    elif t == "order":
        out.update(type="order", items=q["items"])
    else:
        ch = conv.get(f"{tag}:{key}")
        if not ch:
            missing.append(f"{tag}:{key}")
            return out
        out.update(type="mc", choices=ch, answerIndex=0, converted=True)
    return out


WORLDS = [
    ("w1", "U", 0, "BOOT UP", "Unit 1: Computing Systems", "teal"),
    ("w2", "P", 0, "PLAYER ONE", "Pop Culture: Games, Screens & Gadgets", "coral"),
    ("w3", "U", 1, "GO ONLINE", "Unit 2: Networks & the Internet", "violet"),
    ("w4", "P", 1, "LEVEL UP", "Pop Culture: Space, Heroes & Internet Culture", "gold"),
]

worlds = []
for wid, tag, ri, name, sub, color in WORLDS:
    d = banks[tag]
    r = d["rounds"][ri]
    cats = []
    for c in r["categories"]:
        cats.append({
            "id": f"{tag}-{c['id']}",
            "name": c["name"],
            "blurb": c.get("blurb", ""),
            "questions": [norm(tag, q, q["id"]) for q in c["questions"]],
        })
    lightning = [
        norm(tag, s, f"spare{i}")
        for i, s in enumerate(d["spares"])
        if s["categoryId"].startswith(r["id"])
    ]
    worlds.append({
        "id": wid, "name": name, "sub": sub, "color": color, "values": r["values"],
        "art": f"assets/{wid}.jpg", "categories": cats, "lightning": lightning,
    })

speed, finals = [], []
for tag in ("U", "P"):
    d = banks[tag]
    speed += [norm(tag, t, t["id"], 250) for t in d["tiebreakers"]]
    f = d["final"]
    for q in [f["primary"]] + f["backups"]:
        fq = norm(tag, q, q["id"], 0)
        fq["category"] = f["category"]
        finals.append(fq)

if missing:
    sys.exit("Missing MC conversions for: " + ", ".join(missing))

bank = {"worlds": worlds, "speed": speed, "finals": finals}
raw = json.dumps(bank, separators=(",", ":"), ensure_ascii=False).encode()
enc = bytes(b ^ KEY[i % len(KEY)] for i, b in enumerate(raw))
(ROOT / "site" / "bank.js").write_text(
    "/* generated by build.py, edit src/*.json instead */\n"
    f'window.QUEST_BANK="{base64.b64encode(enc).decode()}";\n'
)

n = sum(len(c["questions"]) for w in worlds for c in w["categories"]) + sum(len(w["lightning"]) for w in worlds) + len(speed) + 1
print(f"bank.js written: {len(worlds)} worlds, {n} questions per playthrough "
      f"({sum(1 for w in worlds for c in w['categories'] for q in c['questions'] if q.get('converted'))} board items converted to MC)")
